using System.Globalization;
using System.Text;
using System.Text.Json;
using MenuToOrder.Data;
using MenuToOrder.Extraction;
using MenuToOrder.Verification;

namespace MenuToOrder.Tests.Verification;

// Scores the draft for each sample menu against samples/truth.json, before any owner review.
public class AccuracyTests
{
    private static readonly string[] Menus = ["kose-lokantasi", "sahil-kafe", "mangal-evi"];
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    [Fact]
    public async Task Nothing_misread_or_ambiguous_reaches_the_owner_unflagged()
    {
        foreach (var menu in Menus)
        {
            var score = await Score(menu);
            Assert.True(score.Escaped == 0 && score.Missing == 0, $"{menu}: {string.Join("; ", score.Notes)}");
        }
    }

    // Refreshes docs/accuracy.md: dotnet run --project tests/MenuToOrder.Tests -- -explicit only
    [Fact(Explicit = true)]
    public async Task Write_the_accuracy_report()
    {
        var scores = new List<Tally>();
        foreach (var menu in Menus)
            scores.Add(await Score(menu));
        var all = scores.Aggregate((a, b) => a + b) with { Menu = "**All**" };
        var models = new SortedSet<string>();
        foreach (var menu in Menus)
            models.UnionWith((await Samples.Draft(Guid.CreateVersion7(), menu, Ct)).Runs.Select(r => r.Model.Replace(" (recorded)", "")));

        var md = new StringBuilder()
            .AppendLine("# Accuracy on the sample menus")
            .AppendLine()
            .AppendLine($"Generated by `AccuracyTests` from the `{Prompts.For(1).Version}` and `{Prompts.For(2).Version}` responses recorded with {string.Join(", ", models)}.")
            .AppendLine("Each dish has four fields: name, section, description and price. A price the menu itself")
            .AppendLine("leaves open (\"Sorunuz\", half and full portions, a dollar price) counts as ambiguous: the")
            .AppendLine("right outcome there is a flag, not a number.")
            .AppendLine()
            .AppendLine("| Menu | Dishes | Fields | Read right | Right but flagged | Ambiguous, flagged | Misread, flagged | Reached the page unflagged |")
            .AppendLine("|---|---|---|---|---|---|---|---|");
        foreach (var s in scores.Append(all))
            md.AppendLine($"| {s.Menu} | {s.Dishes} | {s.Fields} | {s.Correct} | {s.CorrectFlagged} | {s.AmbiguousFlagged} | {s.MisreadFlagged} | {s.Escaped} |");

        await File.WriteAllTextAsync(Repo.At("docs", "accuracy.md"), md.ToString(), Ct);
    }

    public sealed record Tally(string Menu, int Dishes, int Fields, int Correct, int CorrectFlagged,
        int AmbiguousFlagged, int MisreadFlagged, int Escaped, int Missing)
    {
        public IReadOnlyList<string> Notes { get; init; } = [];

        public static Tally operator +(Tally a, Tally b) => new(a.Menu, a.Dishes + b.Dishes, a.Fields + b.Fields,
            a.Correct + b.Correct, a.CorrectFlagged + b.CorrectFlagged, a.AmbiguousFlagged + b.AmbiguousFlagged,
            a.MisreadFlagged + b.MisreadFlagged, a.Escaped + b.Escaped, a.Missing + b.Missing) { Notes = [.. a.Notes, .. b.Notes] };
    }

    private static string? Shown(MenuItem item, MenuField field) => field switch
    {
        MenuField.Name => item.Name,
        MenuField.Category => item.Category,
        MenuField.Description => item.Description,
        _ => item.Price?.ToString(CultureInfo.InvariantCulture),
    };

    private sealed record Truth(string Category, string Name, string Printed, string? Lira, string? Description);

    private static async Task<Tally> Score(string menu)
    {
        var truth = JsonSerializer.Deserialize<Dictionary<string, Truth[]>>(
            await File.ReadAllTextAsync(Repo.At("samples", "truth.json"), Ct), JsonSerializerOptions.Web)![menu];
        var draft = await Samples.Draft(Guid.CreateVersion7(), menu, Ct);

        // Two dishes can share a name, so they are matched by name and how often it has come up so far.
        var items = draft.Items.OrderBy(i => i.Position).GroupBy(i => i.Name).ToDictionary(g => g.Key, g => new Queue<MenuItem>(g));
        var tally = new Tally(menu, truth.Length, 0, 0, 0, 0, 0, 0, 0);

        foreach (var dish in truth)
        {
            if (!items.TryGetValue(dish.Name, out var queue) || !queue.TryDequeue(out var item))
            {
                tally = tally with { Missing = tally.Missing + 1, Notes = [.. tally.Notes, $"missing {dish.Name}"] };
                continue;
            }

            var flagged = draft.Flags.Where(f => f.MenuItemId == item.Id).Select(f => f.Field).ToHashSet();
            foreach (var field in Enum.GetValues<MenuField>())
            {
                var isFlagged = flagged.Contains(field);
                bool? right = field switch
                {
                    MenuField.Name => item.Name == dish.Name,
                    MenuField.Category => item.Category == dish.Category,
                    MenuField.Description => item.Description == dish.Description,
                    _ => dish.Lira is null ? null : item.Price == decimal.Parse(dish.Lira, CultureInfo.InvariantCulture),
                };

                tally = (right, isFlagged) switch
                {
                    (true, false) => tally with { Correct = tally.Correct + 1 },
                    (true, true) => tally with { CorrectFlagged = tally.CorrectFlagged + 1 },
                    (null, true) => tally with { AmbiguousFlagged = tally.AmbiguousFlagged + 1 },
                    (false, true) => tally with { MisreadFlagged = tally.MisreadFlagged + 1 },
                    _ => tally with { Escaped = tally.Escaped + 1, Notes = [.. tally.Notes, $"{dish.Name}.{field}: '{Shown(item, field)}'"] },
                };
                tally = tally with { Fields = tally.Fields + 1 };
            }
        }

        // A dish the model invented and nobody flagged would also reach the page.
        var invented = items.Values.SelectMany(q => q).Count(i => !draft.Flags.Any(f => f.MenuItemId == i.Id));
        return tally with { Escaped = tally.Escaped + invented };
    }
}
